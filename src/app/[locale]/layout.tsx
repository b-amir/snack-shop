import type { Metadata } from "next";
import { Vazirmatn } from "next/font/google";
import "../globals.css";
import QueryProvider from "../components/QueryProvider";
import { getMessages } from "next-intl/server";
import { NextIntlClientProvider, useTranslations } from "next-intl";
import styles from "./layout.module.css";

const vazirmatn = Vazirmatn({
  subsets: ["latin", "arabic"],
  display: "swap",
  variable: "--font-vazirmatn",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

function LanguageSwitcher({ locale }: { locale: string }) {
  const otherLocale = locale === "en" ? "fa" : "en";
  return (
    <a
      href={`/${otherLocale}`}
      className={styles.languageSwitcher}
      aria-label="Change language"
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width="20"
        height="20"
        fill="none"
        viewBox="0 0 24 24"
      >
        <circle
          cx="12"
          cy="12"
          r="10"
          stroke="currentColor"
          strokeWidth="2"
          fill="none"
        />
        <path
          d="M2 12h20M12 2c2.5 3.5 2.5 16.5 0 20M12 2c-2.5 3.5-2.5 16.5 0 20"
          stroke="currentColor"
          strokeWidth="2"
          fill="none"
        />
      </svg>
      {otherLocale === "en" ? "English" : "فارسی"}
    </a>
  );
}

function Footer({ locale }: { locale: string }) {
  return (
    <footer className={styles.footer}>
      <div className={styles.footerContent}>
        <LanguageSwitcher locale={locale} />
      </div>
    </footer>
  );
}

function Header({ locale }: { locale: string }) {
  const t = useTranslations();
  const isRTL = locale === "fa";
  const headerContentClass = `${styles.headerContent} ${
    isRTL ? styles.headerContentRtl : styles.headerContentLtr
  }`;

  return (
    <header className={styles.header}>
      <div className={headerContentClass}>
        <h1 className={styles.title}>{t("header")}</h1>
        <p className={styles.subtitle}>{t("subheader")}</p>
      </div>
    </header>
  );
}

export default async function RootLayout({
  children,
  params: { locale },
}: Readonly<{
  children: React.ReactNode;
  params: { locale: string };
}>) {
  const messages = await getMessages();
  return (
    <html
      lang={locale}
      dir={locale === "fa" ? "rtl" : "ltr"}
      className={vazirmatn.variable}
    >
      <body className={styles.body}>
        <NextIntlClientProvider messages={messages}>
          <Header locale={locale} />
          <div className={`container ${styles.mainContainer}`}>
            <QueryProvider>{children}</QueryProvider>
          </div>
          <Footer locale={locale} />
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
